const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/lib/followup-completion.ts'), 'utf8');
const moduleResult = { exports: {} };
new Function('exports', ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText)(moduleResult.exports);
const { followupCompletion, followupAssignee } = moduleResult.exports;
const detail = { status: 'CONTACTED', children: [{ missedServiceDate: '2026-10-04' }], history: [{ eventType: 'CONTACTED', createdAt: '2026-10-05 14:30:00', staffName: 'Daniel James' }] };
assert.deepEqual(followupCompletion(detail), { contactedAt: '2026-10-05 14:30:00', staffName: 'Daniel James', sunday: '2026-10-04' });
assert.equal(followupCompletion({ ...detail, status: 'NEEDS_FOLLOW_UP' }), null);
assert.equal(followupCompletion({ ...detail, status: 'COULDNT_REACH' }), null);
assert.equal(followupCompletion({ ...detail, children: [{ missedServiceDate: '2026-10-11' }] }), null, 'An older contact cannot complete a new Sunday absence');
assert.equal(followupCompletion({ ...detail, status: 'RESOLVED' }).staffName, 'Daniel James');
assert.equal(followupCompletion({ ...detail, history: [], lastContactedAt: '2026-10-06 10:00:00' }).contactedAt, '2026-10-06 10:00:00');
assert.equal(followupCompletion({ ...detail, history: [] }).staffName, null, 'Legacy contacted records remain completed without invented details');
assert.equal(followupAssignee(42), '42');
assert.equal(followupAssignee('42'), '42');
assert.equal(followupAssignee(null), '');
assert.equal(followupAssignee(0), '');
const ui = fs.readFileSync(path.join(root, 'src/components/followup-workspace.tsx'), 'utf8');
assert.match(ui, /useState\(\(\) => followupAssignee\(detail.ownerId\)\)/);
assert.match(ui, /setAssignee\(followupAssignee\(detail.ownerId\)\), \[detail.id, detail.ownerId\]/);
assert.match(ui, /canManage && !completion/);
assert.match(ui, /!completion && <div className="record"/);
console.log('Follow-up completion and saved assignment checks passed (15 cases).');
